using System.Globalization;

namespace SPLog;

internal sealed class LogFileSet
{
    private readonly string _directory;
    private readonly string _baseName;
    private readonly string _extension;
    private readonly FileRollingMode _rollingMode;

    public LogFileSet(string directory, string baseName, string extension, FileRollingMode rollingMode)
    {
        _directory = directory;
        _baseName = baseName;
        _extension = extension;
        _rollingMode = rollingMode;
    }

    public int DetectLastSequence(string periodKey)
    {
        var last = -1;
        foreach (var path in Directory.EnumerateFiles(_directory))
        {
            if (TryParse(path, out var period, out var sequence) && period == periodKey)
            {
                last = Math.Max(last, sequence);
            }
        }
        return last;
    }

    public void Cleanup(int maxFiles, string currentPath)
    {
        var oldFiles = Directory.EnumerateFiles(_directory)
            .Where(path => !FilePathResolver.Comparer.Equals(path, currentPath)
                           && TryParse(path, out _, out _))
            .Select(path => new FileInfo(path))
            .OrderByDescending(info => info.CreationTimeUtc)
            .ThenByDescending(info => info.Name, StringComparer.Ordinal)
            .ToArray();

        // The open file always occupies one retention slot, regardless of its age.
        for (var i = maxFiles - 1; i < oldFiles.Length; i++)
        {
            try
            {
                oldFiles[i].Delete();
            }
            catch
            {
                // Preserve best-effort cleanup when files are locked or inaccessible.
            }
        }
    }

    private bool TryParse(string path, out string period, out int sequence)
    {
        period = string.Empty;
        sequence = 0;
        if (!string.Equals(Path.GetExtension(path), _extension, FilePathResolver.Comparison))
        {
            return false;
        }

        var name = Path.GetFileNameWithoutExtension(path);
        if (!name.StartsWith(_baseName, FilePathResolver.Comparison))
        {
            return false;
        }

        var suffix = name.Substring(_baseName.Length);
        if (_rollingMode == FileRollingMode.Daily || _rollingMode == FileRollingMode.Hourly)
        {
            var length = _rollingMode == FileRollingMode.Daily ? 8 : 11;
            var format = _rollingMode == FileRollingMode.Daily ? "yyyyMMdd" : "yyyyMMdd_HH";
            if (suffix.Length < length + 1 || suffix[0] != '_')
            {
                return false;
            }
            period = suffix.Substring(1, length);
            if (!DateTime.TryParseExact(period, format, CultureInfo.CurrentCulture, DateTimeStyles.None, out _))
            {
                return false;
            }
            suffix = suffix.Substring(length + 1);
        }

        if (suffix.Length == 0)
        {
            return true;
        }

        // Only the exact suffix generated by D3 formatting belongs to this log.
        return suffix[0] == '_'
               && int.TryParse(suffix.Substring(1), NumberStyles.None, CultureInfo.InvariantCulture, out sequence)
               && sequence > 0
               && suffix == "_" + sequence.ToString("D3", CultureInfo.InvariantCulture);
    }
}
